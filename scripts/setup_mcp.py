#!/usr/bin/env python3
"""Write machine-specific MCP registration material for this checkout.

Two jobs, one script:

* ``--host <name>`` prints the exact snippet a host needs (JSON ``mcpServers`` or Codex TOML)
  with this checkout's absolute paths already filled in. Global config files are never written
  unless an explicit ``--write PATH`` is given, because every host keeps its config somewhere
  different and guessing a path is how people lose their existing servers.
* no ``--host`` keeps the historical behaviour: write ``<root>/.mcp.json`` for a project-scoped
  registration (Qoder, Zcode and most project-scoped hosts read exactly that file).

The repository also ships template manifests under ``plugin/`` with ``<RESEARCH_AGENT_ROOT>``
placeholders; those stay machine-independent and are regenerated by ``research_agent plugin export``.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import tempfile
import time
from pathlib import Path

HOSTS = {
    "qoder": {
        "format": "json",
        "manifest": "plugin/mcp.qoder.json",
        "where": "Qoder MCP settings (project scope reads <project>/.mcp.json; else paste this server entry)",
    },
    "zcode": {
        "format": "json",
        "manifest": "plugin/mcp.zcode.json",
        "where": "Zcode MCP settings",
    },
    "codex": {
        "format": "toml",
        "manifest": "plugin/mcp.codex.toml",
        "where": "~/.codex/config.toml (append the block; do not replace the file)",
    },
    "workbuddy": {
        "format": "json",
        "manifest": "plugin/mcp.workbuddy.json",
        "where": "WorkBuddy connector settings (verify the expected shape against its docs; the JSON below is the standard mcpServers shape)",
    },
    "claude-code": {
        "format": "json",
        "manifest": "",
        "where": "claude mcp add-json research-agent '<json>' or ~/.claude.json",
    },
    "cursor": {
        "format": "json",
        "manifest": "",
        "where": "~/.cursor/mcp.json (mcpServers key)",
    },
    "cline": {
        "format": "json",
        "manifest": "",
        "where": "Cline MCP settings (mcpServers key)",
    },
    "continue": {
        "format": "json",
        "manifest": "",
        "where": "Continue config (mcpServers key; check your Continue version's format)",
    },
    "zed": {
        "format": "json",
        "manifest": "",
        "where": "Zed context servers settings (check the exact key; Zed may use context_servers)",
    },
}


def build_config(root: Path) -> dict:
    root = Path(root).resolve()
    launcher = root / "scripts" / "research_mcp_server.py"
    if not launcher.is_file():
        raise FileNotFoundError("missing MCP launcher: %s" % launcher)
    root_posix = root.as_posix()
    return {
        "mcpServers": {
            "research-agent": {
                "type": "stdio",
                "command": "python",
                "args": [launcher.as_posix(), "--root", root_posix],
                "env": {
                    "PYTHONPATH": root_posix,
                    "RESEARCH_AGENT_MCP_ROOT": root_posix,
                    "PYTHONIOENCODING": "utf-8",
                },
            }
        }
    }


def build_toml(root: Path) -> str:
    root = Path(root).resolve()
    launcher = root / "scripts" / "research_mcp_server.py"
    if not launcher.is_file():
        raise FileNotFoundError("missing MCP launcher: %s" % launcher)
    root_posix = root.as_posix()
    return (
        "# Codex registers MCP servers in ~/.codex/config.toml\n"
        "[mcp_servers.research-agent]\n"
        'command = "python"\n'
        'args = ["%s/scripts/research_mcp_server.py", "--root", "%s"]\n'
        "\n"
        "[mcp_servers.research-agent.env]\n"
        'PYTHONPATH = "%s"\n'
        'PYTHONIOENCODING = "utf-8"\n' % (root_posix, root_posix, root_posix)
    )


def render_host(host: str, root: Path) -> tuple:
    """Return (text, where, fmt) for one host, paths already filled."""
    spec = HOSTS[host]
    if spec["format"] == "toml":
        return build_toml(root), spec["where"], "toml"
    config = build_config(root)
    return (
        json.dumps(config, ensure_ascii=False, indent=2) + "\n",
        spec["where"],
        "json",
    )


def _replace_with_retry(temp_name: str, path: Path) -> None:
    """Windows can deny the rename while a scanner still holds the destination it just wrote."""
    for attempt in range(4):
        try:
            os.replace(temp_name, path)
            return
        except PermissionError:
            if attempt == 3:
                raise
            time.sleep(0.05 * (attempt + 1))


def _write_atomic(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, temp_name = tempfile.mkstemp(prefix=".mcp-", suffix=".json", dir=str(path.parent))
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
            handle.flush()
            os.fsync(handle.fileno())
        _replace_with_retry(temp_name, path)
    except BaseException:
        try:
            os.unlink(temp_name)
        except OSError:
            pass
        raise


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", default=Path(__file__).resolve().parents[1])
    parser.add_argument("--host", choices=sorted(HOSTS), help="render the snippet for one host")
    parser.add_argument("--list", action="store_true", help="list supported hosts and exit")
    parser.add_argument("--output", help="default: <root>/.mcp.json")
    parser.add_argument(
        "--write", help="write the host snippet to this exact path; global configs are never guessed"
    )
    parser.add_argument("--force", action="store_true", help="overwrite an existing file")
    parser.add_argument("--print", action="store_true", help="print the config without writing")
    args = parser.parse_args(argv)

    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8")

    root = Path(args.root).resolve()

    if args.list:
        for name, spec in HOSTS.items():
            manifest = ("in-repo template: " + spec["manifest"]) if spec["manifest"] else "(no in-repo template)"
            print("%-12s %-5s %s | %s" % (name, spec["format"], manifest, spec["where"]))
        return 0

    try:
        if args.host:
            text, where, fmt = render_host(args.host, root)
            if args.print or not args.write:
                print("# host: %s\n# put it here: %s\n" % (args.host, where))
                sys.stdout.write(text)
                if not args.write:
                    print("# nothing written; pass --write PATH to save it")
                    return 0
            output = Path(args.write).resolve()
            if output.exists() and not args.force:
                print(
                    "refusing to overwrite %s; pass --force or use a different --write" % output,
                    file=sys.stderr,
                )
                return 1
            _write_atomic(output, text)
            print("wrote %s (%s, host %s)" % (output, fmt, args.host))
            print("next: reload MCP in %s and confirm the research-agent server" % args.host)
            return 0

        # Historical default: project-scoped .mcp.json
        output = Path(args.output).resolve() if args.output else root / ".mcp.json"
        config = build_config(root)
        text = json.dumps(config, ensure_ascii=False, indent=2) + "\n"
        if args.print:
            sys.stdout.write(text)
            return 0
        if output.exists() and not args.force:
            print(
                "refusing to overwrite %s; pass --force or use a different --output" % output,
                file=sys.stderr,
            )
            return 1
        _write_atomic(output, text)
        print("wrote %s" % output)
        print("next: reload MCP in your client and confirm the research-agent server")
        return 0
    except FileNotFoundError as exc:
        print(str(exc), file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
