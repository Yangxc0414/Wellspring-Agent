"""Demonstrate external-skill invocation and local distillation without a model key.

The demo creates a small local skill with a script, references and an asset,
runs it with explicit trusted-script opt-in, then distills it into a disabled
local candidate. It never enables the candidate.
"""

import json
import sys
from datetime import datetime, timezone
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from research_agent.external_skills import invoke_external_skill
from research_agent.skill_distill import distill_skill
from research_agent.skill_registry import SkillRegistryStore


SKILL_MD = """---
name: claim-check-demo
description: Use when checking that result sentences have evidence references.
version: 0.1.0
license: MIT
allowed-tools: evidence.inspect
---

# Claim check demo

Use this skill to verify that every result sentence in a draft points to a
locatable evidence span. It is advisory only and never creates a claim.
"""

RUN_PY = """import json
import sys
from pathlib import Path

payload = json.load(sys.stdin)
mode = sys.argv[1] if len(sys.argv) > 1 else "default"
Path("script-proof.json").write_text(
    json.dumps({"mode": mode, "input": payload["input"]}, ensure_ascii=False),
    encoding="utf-8",
)
print(json.dumps({
    "status": "advisory_only",
    "mode": mode,
    "args": sys.argv[1:],
    "echo": payload["input"],
    "suggested_checks": ["every result sentence has a span ref"],
}))
"""


def _write_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with open(str(path), "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def prepare(root: Path) -> Path:
    skill_dir = root / "sample-skill"
    _write_text(skill_dir / "SKILL.md", SKILL_MD)
    _write_text(skill_dir / "scripts" / "run.py", RUN_PY)
    _write_text(
        skill_dir / "references" / "checklist.md",
        "# Checklist\n\n1. Every result sentence has a locatable span.\n",
    )
    _write_text(
        skill_dir / "assets" / "report-note.txt",
        "Advisory note generated by the external skill demo.\n",
    )
    return skill_dir


def main() -> int:
    root = ROOT / "runtime_data" / "integrations" / "external-skill-demo"
    root.mkdir(parents=True, exist_ok=True)
    skill_dir = prepare(root)
    registry_path = root / "skills.json"
    store = SkillRegistryStore(registry_path)
    imported = store.import_directory(skill_dir)
    record = next(
        (
            item
            for item in store.list()
            if item.get("name") == "claim-check-demo"
        ),
        None,
    )
    if record is None:
        raise SystemExit("demo skill was not imported: " + json.dumps(imported["rejected"]))
    store.set_enabled(record["id"], True)

    workdir = root / "work"
    workdir.mkdir(parents=True, exist_ok=True)
    invocation = invoke_external_skill(
        skill_id=record["id"],
        input_text="Check the result paragraph about humidity stability.",
        trusted_scripts=True,
        workdir=str(workdir),
        script_args=["review"],
        registry_path=str(registry_path),
        usage_path=str(root / "usage.json"),
        output_path=str(root / "invocation.json"),
    )
    distilled = distill_skill(
        skill_id=record["id"],
        library_dir=root / "library",
        registry_path=registry_path,
        human_reason="Demo: reuse the claim-evidence checklist in local projects",
        source_url="local://claim-check-demo",
    )
    candidate = distilled["candidate"]
    after = store.snapshot()
    candidate_record = next(
        (
            item
            for item in after["skills"]
            if item.get("id") == candidate.get("registered_skill_id")
        ),
        {},
    )
    summary = {
        "schema_version": "external-skill-integration-demo-0.1",
        "created_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "skill": {
            "id": record["id"],
            "name": record["name"],
            "license": record["license"],
            "enabled": True,
            "has_scripts": record["has_scripts"],
        },
        "scan": {
            "accepted": [item.get("name") for item in imported.get("accepted", [])],
            "rejected": imported.get("rejected", []),
        },
        "invocation": {
            "execution_mode": invocation["execution_mode"],
            "output": invocation["output"],
            "returncode": invocation["returncode"],
            "evidence_eligible": invocation["evidence_eligible"],
            "usage": invocation["usage"],
            "workdir_proof": str(workdir / "script-proof.json"),
        },
        "distillation": {
            "created": distilled["created"],
            "candidate": candidate,
            "candidate_registry_enabled": bool(candidate_record.get("enabled")),
            "candidate_license": candidate.get("license"),
            "candidate_files": [item["path"] for item in candidate.get("files", [])],
        },
        "review_command": (
            "python -m research_agent skill enable %s --registry-path %s"
            % (candidate_record.get("id", ""), registry_path)
        ),
        "boundary": (
            "external script ran locally with the user's OS permissions and is not a sandbox; "
            "the distilled candidate stays disabled until a human reviews and enables it"
        ),
    }
    _write_text(
        root / "summary.json",
        json.dumps(summary, ensure_ascii=False, indent=2) + "\n",
    )
    lines = [
        "# External Skill Integration Demo",
        "",
        "- skill: `%s` (%s)" % (record["name"], record["id"]),
        "- execution: `%s` (trusted local script, not sandbox)" % invocation["execution_mode"],
        "- script args: `%s`" % ", ".join(invocation["output"].get("args", [])),
        "- script proof: `%s`" % (workdir / "script-proof.json"),
        "- invocation receipt: `%s`" % (root / "invocation.json"),
        "- distilled candidate: `%s`" % distilled["path"],
        "- candidate files: %s"
        % ", ".join("`%s`" % item["path"] for item in candidate.get("files", [])),
        "- candidate enabled: `%s` (must stay false until human review)"
        % bool(candidate_record.get("enabled")),
        "",
        "## Human review",
        "",
        "```bash",
        summary["review_command"],
        "```",
        "",
        "Boundary: " + summary["boundary"] + ".",
        "",
    ]
    _write_text(root / "summary.md", "\n".join(lines))
    print(json.dumps(summary, ensure_ascii=False, indent=2))
    print("\nSaved:", root / "summary.json")
    return 0 if not candidate_record.get("enabled") else 1


if __name__ == "__main__":
    raise SystemExit(main())
